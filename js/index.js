function setPortfolioView(view) {
    document.getElementById('section_web').style.display = view === 'web' ? '' : 'none';
    document.getElementById('section_wordpress').style.display = view === 'wordpress' ? '' : 'none';
    document.getElementById('section_desarrollo').style.display = view === 'desarrollo' ? '' : 'none';
    document.getElementById('button_paginas').classList.toggle('active', view === 'web');
    document.getElementById('button_wordpress').classList.toggle('active', view === 'wordpress');
    document.getElementById('button_desarrollo').classList.toggle('active', view === 'desarrollo');
}

document.getElementById('button_paginas').addEventListener('click', function () {
    setPortfolioView('web');
});

document.getElementById('button_wordpress').addEventListener('click', function () {
    setPortfolioView('wordpress');
    Wordpress();
});

document.getElementById('button_desarrollo').addEventListener('click', function () {
    setPortfolioView('desarrollo');
    Desarrollo();
});

